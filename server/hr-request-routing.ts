import type { PoolClient } from "pg";
import { pool } from "./db";

export type RequestKind = "leave" | "permission";
export type ApprovalSnapshot = {
  version: number; managerReview: boolean; requireManager: boolean;
  managerEmployeeId: number | null; managerUserId: number | null; capturedAt: string;
  fallbackReason?: "manager_unassigned" | "manager_account_unavailable" | null;
};
const fail = (status:number,message:string):never => {throw Object.assign(new Error(message),{status});};
export const requestTable = (kind:RequestKind) => kind==="leave" ? "leave_requests" : "attendance_permissions";
export const requestDataColumn = (kind:RequestKind) => kind==="leave" ? "leave_form_data" : "form_details";
export function approvalSnapshot(value:unknown):ApprovalSnapshot|null {
  const s=(value as any)?._approval;
  return s && Number.isInteger(s.version) && typeof s.managerReview==="boolean"
    ? s as ApprovalSnapshot : null;
}
export function effectiveRequestManager(data:unknown,legacy:{manager_id?:number|null;manager_user_id?:number|null}) {
  const snapshot=approvalSnapshot(data);
  return snapshot ? {manager_id:snapshot.managerReview?snapshot.managerEmployeeId:null,
    manager_user_id:snapshot.managerReview?snapshot.managerUserId:null} : legacy;
}
export async function captureRequestRouting(kind:RequestKind,employeeId:number,data:unknown,client:Pick<PoolClient,"query">=pool) {
  const {rows:[setting]}=await client.query(`SELECT manager_review,require_manager,version FROM hr_request_settings WHERE kind=$1`,[kind]);
  const {rows:[employee]}=await client.query(`SELECT e.id,m.id AS manager_id,m.user_id AS manager_user_id,
    u.active,u.archived FROM employees e LEFT JOIN employees m ON m.id=e.manager_id AND m.id<>e.id AND m.status='active'
    LEFT JOIN users u ON u.id=m.user_id WHERE e.id=$1`,[employeeId]);
  if(!employee)fail(404,"الموظف غير موجود.");
  const managerReview=setting?.manager_review??true,requireManager=setting?.require_manager??false;
  const usableManager=!!(employee.manager_id&&employee.manager_user_id&&employee.active&&!employee.archived);
  if(managerReview&&requireManager&&!usableManager)
    fail(409,"يلزم ربط الموظف بمدير مباشر ذي حساب نشط قبل تقديم الطلب. راجع الموارد البشرية.");
  const snapshot:ApprovalSnapshot={version:setting?.version??0,managerReview,requireManager,
    managerEmployeeId:managerReview&&usableManager?employee.manager_id:null,
    managerUserId:managerReview&&usableManager?employee.manager_user_id:null,capturedAt:new Date().toISOString(),
    fallbackReason:managerReview&&!usableManager?(employee.manager_id?"manager_account_unavailable":"manager_unassigned"):null};
  // Reserved metadata is always generated by the server, never accepted from a form.
  const {_approval,_attachments,...safe}=data&&typeof data==="object"&&!Array.isArray(data)?data as Record<string,unknown>:{};
  return {...safe,_approval:snapshot};
}

export async function getRequestSettings() {
  const {rows}=await pool.query(`SELECT kind,manager_review AS "managerReview",require_manager AS "requireManager",
    version,updated_at AS "updatedAt" FROM hr_request_settings ORDER BY kind`);
  return {items:(["leave","permission"] as const).map(kind=>rows.find(r=>r.kind===kind)||
    {kind,managerReview:true,requireManager:false,version:0,updatedAt:null})};
}
export async function saveRequestSettings(kind:RequestKind,input:{managerReview:boolean;requireManager:boolean;version:number},
  userId:number|null,client:Pick<PoolClient,"query">=pool) {
  if(!input.managerReview&&input.requireManager)fail(400,"لا يمكن اشتراط المدير في مسار الموارد البشرية فقط.");
  const returning=`RETURNING kind,manager_review AS "managerReview",require_manager AS "requireManager",version,updated_at AS "updatedAt"`;
  const sql=input.version===0?`INSERT INTO hr_request_settings(kind,manager_review,require_manager,version,updated_by)
    SELECT $1,$2,$3,1,$4 WHERE $5=0 ON CONFLICT(kind) DO NOTHING ${returning}`:
    `UPDATE hr_request_settings SET manager_review=$2,require_manager=$3,version=version+1,updated_by=$4,updated_at=now()
    WHERE kind=$1 AND version=$5 ${returning}`;
  const {rows:[row]}=await client.query(sql,[kind,input.managerReview,input.requireManager,userId,input.version]);
  if(!row)fail(409,"غيّر مسؤول آخر الإعداد. حدّث الصفحة ثم أعد المحاولة.");
  return row;
}
